CREATE TABLE harvest_disposition_audits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cultivation_plan_id BIGINT NOT NULL REFERENCES cultivation_plans (id),
    farmer_id BIGINT NOT NULL REFERENCES farmers (id),
    action VARCHAR(24) NOT NULL,
    previous_sold_quantity NUMERIC(14, 3) NOT NULL,
    previous_stored_quantity NUMERIC(14, 3) NOT NULL,
    previous_discarded_quantity NUMERIC(14, 3) NOT NULL,
    sold_quantity NUMERIC(14, 3) NOT NULL,
    stored_quantity NUMERIC(14, 3) NOT NULL,
    discarded_quantity NUMERIC(14, 3) NOT NULL,
    changed_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_harvest_disposition_audits_plan_changed
    ON harvest_disposition_audits (cultivation_plan_id, changed_at DESC, id DESC);

INSERT INTO harvest_disposition_audits (
    cultivation_plan_id, farmer_id, action,
    previous_sold_quantity, previous_stored_quantity, previous_discarded_quantity,
    sold_quantity, stored_quantity, discarded_quantity, changed_at
)
SELECT id, farmer_id, 'BASELINE_IMPORTED', 0, 0, 0,
       sold_quantity, stored_quantity, discarded_quantity, CURRENT_TIMESTAMP
FROM cultivation_plans
WHERE actual_harvest_quantity IS NOT NULL;
