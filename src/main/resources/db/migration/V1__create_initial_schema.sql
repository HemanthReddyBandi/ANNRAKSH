CREATE TABLE farmers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    email VARCHAR(254) NOT NULL UNIQUE,
    phone VARCHAR(30),
    password_hash VARCHAR(60) NOT NULL,
    role VARCHAR(20) NOT NULL,
    location VARCHAR(160),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE crops (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    category VARCHAR(80) NOT NULL,
    season VARCHAR(120) NOT NULL,
    average_growth_days INTEGER NOT NULL
);

CREATE TABLE crop_demand (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    crop_id BIGINT NOT NULL REFERENCES crops (id),
    location VARCHAR(160) NOT NULL,
    demand_level VARCHAR(20) NOT NULL,
    demand_quantity NUMERIC(14, 3) NOT NULL,
    supply_quantity NUMERIC(14, 3) NOT NULL,
    quantity_unit VARCHAR(20) NOT NULL,
    recorded_date DATE NOT NULL
);

CREATE TABLE cultivation_plans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farmer_id BIGINT NOT NULL REFERENCES farmers (id),
    crop_id BIGINT NOT NULL REFERENCES crops (id),
    area_hectares NUMERIC(12, 3) NOT NULL,
    planned_quantity NUMERIC(14, 3) NOT NULL,
    actual_harvest_quantity NUMERIC(14, 3),
    quantity_unit VARCHAR(20) NOT NULL,
    planting_date DATE NOT NULL,
    expected_harvest_date DATE NOT NULL,
    actual_harvest_date DATE,
    status VARCHAR(20) NOT NULL
);

CREATE TABLE recommendations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farmer_id BIGINT NOT NULL REFERENCES farmers (id),
    crop_id BIGINT NOT NULL REFERENCES crops (id),
    score INTEGER NOT NULL,
    market_score INTEGER NOT NULL,
    season_score INTEGER NOT NULL,
    historical_performance_score INTEGER NOT NULL,
    demand_recorded_date DATE NOT NULL,
    demand_level VARCHAR(20) NOT NULL,
    decision VARCHAR(24) NOT NULL,
    reason VARCHAR(1000) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
